-- Enable the necessary extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==========================================
-- 1. PROFILES
-- ==========================================
CREATE TABLE public.profiles (
  id uuid REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  first_name text,
  last_name text,
  email text,
  role text DEFAULT 'customer', -- 'customer' or 'admin'
  has_scanned boolean DEFAULT false,
  measurements jsonb DEFAULT '{}'::jsonb,
  brand_sizes jsonb DEFAULT '{}'::jsonb,
  style_prefs text[] DEFAULT '{}',
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- 2. PRODUCTS
-- ==========================================
CREATE TABLE public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  brand text NOT NULL,
  category text NOT NULL,
  gender text DEFAULT 'Unisex',
  price numeric NOT NULL,
  original_price numeric,
  images text[] NOT NULL,
  colors text[] DEFAULT '{}',
  sizes text[] DEFAULT '{}',
  rating numeric DEFAULT 0,
  reviews integer DEFAULT 0,
  fabric text,
  care text,
  description text,
  tags text[] DEFAULT '{}',
  in_stock boolean DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- 3. ORDERS
-- ==========================================
CREATE TABLE public.orders (
  id uuid DEFAULT uuid_generate_v4() PRIMARY KEY,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE,
  status text DEFAULT 'Pending', -- 'Pending', 'Paid', 'Dispatched', 'Delivered'
  total_amount numeric NOT NULL,
  shipping_address jsonb NOT NULL,
  items jsonb NOT NULL, -- array of { product_id, size, quantity, price }
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- 4. REVIEWS
-- ==========================================
CREATE TABLE public.reviews (
  id uuid DEFAULT uuid_generate_v4() PRIMARY KEY,
  product_id bigint REFERENCES public.products(id) ON DELETE CASCADE,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE,
  rating integer CHECK (rating >= 1 AND rating <= 5),
  comment text,
  images text[] DEFAULT '{}',
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- 5. DELIVERIES (Tracking)
-- ==========================================
CREATE TABLE public.deliveries (
  id uuid DEFAULT uuid_generate_v4() PRIMARY KEY,
  order_id uuid REFERENCES public.orders(id) ON DELETE CASCADE,
  agent_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL, -- the delivery driver
  status text DEFAULT 'Preparing', -- 'Preparing', 'In Transit', 'Delivered'
  current_lat numeric,
  current_lng numeric,
  last_updated timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- 6. SHONA DICTIONARY (For AI Search)
-- ==========================================
CREATE TABLE public.shona_dictionary (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shona_term text UNIQUE NOT NULL,
  english_translation text NOT NULL
);

